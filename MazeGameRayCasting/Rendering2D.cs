using MazeGame_v2;
using System;
using System.Collections.Generic;
using System.Drawing;
using System.Linq;
using System.Numerics;
using System.Runtime.CompilerServices;
using System.Text;
using System.Threading.Tasks;

namespace MazeGameRayCasting
{
    internal class Rendering2D
    {
        public void RenderMaze2D(int[,] maze)
        {
            for (int x = 0; x < maze.GetLength(0); x++) //Looping through the maze grid generated by the maze (this.maze) from the MazeGenerator class
            {
                for (int y = 0; y < maze.GetLength(1); y++)
                {
                    ConsoleColor colour = maze[x, y] switch //Using a switch case to choose colour based on the number used to represent different colours 
                    {
                        0 => ConsoleColor.DarkBlue, //Black = wall
                        1 => (x + y) % 2 == 0 ? ConsoleColor.White : ConsoleColor.Gray, //Using ternary operators to draw a grid pattern out of white and light grey, just for visibility of tiles
                        2 => ConsoleColor.Green, //Green = Startpoint
                        3 => ConsoleColor.Red, //Red = Endpoint
                        _ => ConsoleColor.DarkGray //Using grey as a fallback incase of a number in maze not matching any switch case (good for error detecting because it shows up)
                    };
                    Console.ForegroundColor = colour;
                    Console.BackgroundColor = colour;
                    Console.Write("##");
                }
                Console.WriteLine();
            }
            Console.ForegroundColor = ConsoleColor.White;
            Console.BackgroundColor = ConsoleColor.Black;
        }
    }
}
